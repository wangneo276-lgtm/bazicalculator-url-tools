    public static function canonicalUrl(string $input): string
    {
        $raw = trim($input);
        if ($raw === '') throw new \InvalidArgumentException('path required');
        if (str_contains($raw, '\\') || str_contains($raw, '%')) throw new \InvalidArgumentException('invalid path');
        $raw = explode('#', $raw, 2)[0];
        $raw = explode('?', $raw, 2)[0];
        $lower = strtolower($raw);
        if (str_starts_with($lower, 'https://') || str_starts_with($lower, 'http://') || str_starts_with($raw, '//')) {
            $rest = str_starts_with($lower, 'https://') ? substr($raw, 8) : (str_starts_with($lower, 'http://') ? substr($raw, 7) : substr($raw, 2));
            $slash = strpos($rest, '/');
            $hostport = $slash === false ? $rest : substr($rest, 0, $slash);
            $path = $slash === false ? '/' : substr($rest, $slash);
            if (str_contains($hostport, '@') || str_contains($hostport, ':') || strtolower($hostport) !== self::HOST) {
                throw new \InvalidArgumentException('host not allowed');
            }
        } elseif (str_starts_with($raw, '/')) {
            $path = $raw;
        } else {
            $path = '/' . $raw;
        }
        $path = strtolower($path);
        while (str_contains($path, '//')) $path = str_replace('//', '/', $path);
        if (strlen($path) > 1) $path = rtrim($path, '/');
        if ($path === '') $path = '/';
        if (!isset(self::PATHS[$path])) throw new \InvalidArgumentException('unknown path');
        return $path === '/' ? self::ORIGIN . '/' : self::ORIGIN . $path;
    }
    public static function homeUrl(): string { return self::canonicalUrl('/'); }
    public static function pageUrl(string $key): string {
        if (!isset(self::PAGES[$key])) throw new \InvalidArgumentException('unknown page');
        return self::canonicalUrl(self::PAGES[$key]);
    }
    public static function blogUrl(string $slug): string {
        if (!isset(self::BLOGS[$slug])) throw new \InvalidArgumentException('unknown blog');
        return self::canonicalUrl(self::BLOGS[$slug]);
    }
    public static function localeUrl(string $locale, string $key): string {
        if ($locale !== 'en' && $locale !== 'zh') throw new \InvalidArgumentException('locale not available');
        if (!isset(self::PAGES[$key])) throw new \InvalidArgumentException('unknown page');
        $path = self::PAGES[$key];
        if ($locale === 'zh' && isset(self::ENGLISH_ONLY[$path])) throw new \InvalidArgumentException('locale not available');
        if ($locale === 'en') return self::canonicalUrl($path);
        return self::canonicalUrl($path === '/' ? '/zh' : '/zh' . $path);
    }
